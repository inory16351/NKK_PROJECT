RANK_MUL_LO, RANK_MUL_HI = 1.115, 1.48
def rank_step(t): return 1.0 if t <= 1 else RANK_MUL_LO + (RANK_MUL_HI - RANK_MUL_LO) * (t - 2) / 14
def rank_mul(t):
    m = 1.0
    for k in range(2, t + 1): m *= rank_step(k)
    return m
def rank_k(t): return RANK_K_T.get(t, RANK_K)

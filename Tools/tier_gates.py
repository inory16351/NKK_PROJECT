# 훈장 승급 배율 (2026-10-26): 승급할 때마다 모든 쥐 공격력 × rank_step(t), 누적 = rank_mul(t) → 티어 테이블 rank_mul 칸 · Rat.Damage (CommonSkill.RankMul)
